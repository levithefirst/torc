// npm run docs:deployments   Regenerates docs/DEPLOYMENTS.md from deployments/*.json (public records only).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const explorer = (net: string, txid: string) => (net === 'mainnet' ? `https://explorer.bitcoinunlimited.info/tx/${txid}` : `https://chipnet.imaginary.cash/tx/${txid}`);
const lines: string[] = ['# Deployments', '', 'Generated by `npm run docs:deployments` from the public records in `deployments/`. Every txid links to an explorer.', ''];
const asset = existsSync('deployments/chipnet-asset.json') ? JSON.parse(readFileSync('deployments/chipnet-asset.json', 'utf8')) : null;
if (asset) {
  lines.push('## Chipnet test asset: tPUSD', '', `- Category: \`${asset.category}\` (2 decimals, like mainnet PUSD)`, `- Genesis: [${asset.genesisTxid}](${explorer('chipnet', asset.genesisTxid)})`, `- Distribution to demo seats: [${asset.distributionTxid}](${explorer('chipnet', asset.distributionTxid)})`, '');
}
for (const f of readdirSync('deployments').filter((f) => f.endsWith('.json') && !f.includes('asset')).sort()) {
  const r = JSON.parse(readFileSync(`deployments/${f}`, 'utf8'));
  const p = r.params;
  const claims = r.events.filter((e: any) => e.kind === 'claim').length;
  lines.push(`## ${r.name} (${r.network}) · \`deployments/${f}\``, '');
  lines.push(`- Covenant (token-aware): \`${r.covenantTokenAddress}\``);
  lines.push(`- Covenant (P2SH32): \`${r.covenantAddress}\``);
  lines.push(`- Circle category: \`${p.circleCategory}\``);
  lines.push(`- Params: ${p.seats} seats · ${p.mode === 'token' ? `${Number(p.contribution) / 10 ** (r.assetDecimals ?? 0)} ${r.assetName} (${p.contribution} base units)` : `${p.contribution} sats`} each · period ${p.period} s`);
  lines.push(`- Seats: ${r.seatNames.map((n: string, i: number) => `${i + 1}. ${n}`).join(', ')}${r.seatKeys?.length ? ` (CLI throwaway keys: ${r.seatKeys.join(', ')})` : ' (server-derived demo keys)'}`);
  lines.push(`- Full rounds completed (claims): **${claims}**`, '');
  lines.push('| # | When (UTC) | Action | Seat | Round | Tx |', '|---|---|---|---|---|---|');
  r.events.forEach((e: any, i: number) => {
    const seat = e.seat === undefined ? '' : `${e.seat + 1} ${r.seatNames[e.seat] ?? ''}`;
    lines.push(`| ${i + 1} | ${e.at.replace('T', ' ').slice(0, 19)} | ${e.kind} | ${seat} | ${e.round === undefined ? '' : e.round + 1} | [${e.txid.slice(0, 10)}…](${explorer(r.network, e.txid)}) |`);
  });
  lines.push('');
}
lines.push('Web demo circle actions triggered from the site ("Run the next step live") are not in the table above; they are on chain at the covenant address and in the live feed.', '');
writeFileSync('docs/DEPLOYMENTS.md', lines.join('\n'));
console.log('wrote docs/DEPLOYMENTS.md');
